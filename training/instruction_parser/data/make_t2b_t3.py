SHAPE = {"cube": "cube", "cyl": "cylinder", "tri": "triangle"}
COL = ("red", "yellow", "blue")


def spec(rules: str) -> dict:
    out = {"rules": [], "other": "leave"}
    for seg in rules.split(";"):
        seg = seg.strip()
        if not seg:
            continue
        lhs, to = (x.strip() for x in seg.split(">"))
        assert to in ("left", "center", "right", "leave"), seg
        if lhs == "other":
            out["other"] = to
            continue
        words = lhs.split()
        cols = [w for w in words if w in COL]
        shps = [SHAPE[w] for w in words if w in SHAPE]
        assert all(w in COL or w in SHAPE or w == "all" for w in words), seg
        out["rules"].append({"colors": cols or None, "shapes": shps or None, "to": to})
    return out


