"""Generate the venue-look assets next to this file.

    python make_assets.py                                              # plywood.png (table-top texture, 1 px = 1 mm)
    python make_assets.py <aalto>/aaltonomous/scene/scene.yaml 0.03    # also scene_venue.yaml with a 3 cm bin gap

plywood.png: procedural varnished plywood in the tone sampled from the venue photo (see venue.yaml).
scene_venue.yaml (optional, only once someone has MEASURED the real table): Aalto's scene.yaml with the gap between
neighbouring bins set to the given value in metres. Aalto's published gap is 5 cm; the photo can't settle it.
Geometry affects scoring and the oracle, so every process must use the same file (AALTO_SCENE for the sim AND for
every client: check, eval, baseline).
"""
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
BASE = np.array([196, 152, 122], float)          # sRGB plywood tone


def plywood(w=1100, h=600, seed=0):
    """(h, w, 3) uint8. Grain runs along the long axis (the robot's left-right)."""
    import cv2
    rng = np.random.default_rng(seed)
    y = np.linspace(0, 1, h)[:, None]
    x = np.linspace(0, 1, w)[None, :]
    # wide, slowly wandering growth bands + fine grain lines
    warp = 0.03 * np.sin(2 * np.pi * (1.3 * x + 0.2)) + 0.015 * np.sin(2 * np.pi * (3.1 * x + 0.7))
    bands = 0.5 + 0.5 * np.sin(2 * np.pi * 7 * (y + warp))
    bands2 = 0.5 + 0.5 * np.sin(2 * np.pi * 23 * (y + 0.6 * warp) + 1.0)
    fine = cv2.GaussianBlur(rng.normal(0, 1, (h, w)).astype(np.float32), (0, 0), sigmaX=40, sigmaY=0.8)
    fine /= np.abs(fine).max()
    blotch = cv2.GaussianBlur(rng.normal(0, 1, (h, w)).astype(np.float32), (0, 0), sigmaX=120, sigmaY=80)
    blotch /= np.abs(blotch).max()
    v = 1.0 + 0.035 * (bands - 0.5) + 0.02 * (bands2 - 0.5) + 0.05 * fine + 0.04 * blotch
    img = BASE[None, None, :] * v[..., None]
    img[..., 2] *= 1.0 - 0.03 * (bands - 0.5)[..., ]          # darker bands are a little redder
    img = np.clip(img, 0, 255).astype(np.uint8)
    # a few zinc screw heads, like the real top
    for _ in range(9):
        c = (int(rng.uniform(40, w - 40)), int(rng.uniform(40, h - 40)))
        cv2.circle(img, c, 6, (150, 150, 155), -1, cv2.LINE_AA)
        cv2.circle(img, c, 6, (110, 108, 105), 1, cv2.LINE_AA)
    return img


def scene_venue(src, gap):
    import yaml
    sc = yaml.safe_load(open(src))
    b = sc["bins"]
    step = float(b["outer_size"][0]) + gap
    cx, cy = b["centers"]["center"]
    b["centers"] = {"left": [round(cx + step, 4), cy], "center": [cx, cy], "right": [round(cx - step, 4), cy]}
    out = HERE / "scene_venue.yaml"
    out.write_text(f"# GENERATED by make_assets.py from Aalto's scene.yaml. Only change: bin gap = {gap * 100:.1f} cm.\n"
                   + yaml.safe_dump(sc, sort_keys=False))
    print("wrote", out, b["centers"])


if __name__ == "__main__":
    import cv2
    cv2.imwrite(str(HERE / "plywood.png"), plywood()[..., ::-1])
    print("wrote", HERE / "plywood.png")
    if len(sys.argv) > 2:
        scene_venue(sys.argv[1], float(sys.argv[2]))
