"""Build the MuJoCo venue scene from venue_measured.yaml: Unitree's G1 + Dex3 MJCF (fixed pelvis, 28 position-controlled
arm/hand joints, a head D435 camera), the table, three bins and Aalto's 18 objects (parked until a layout uses them).

    python sim/mujoco/build.py [--colors venue|sim|real_camera] [--xml out.xml]   # writes the model, prints a summary

Used by backend.py. Geometry that the scorer and (optionally) the policy need is written as a scene.yaml in Aalto's
format: artifacts/mujoco/scene_measured.yaml (Aalto's scene.yaml + the measured bins + the venue layout region).
"""
from __future__ import annotations

import argparse
import copy
import os
import sys
from pathlib import Path

import mujoco
import numpy as np
import yaml

ROOT = Path(__file__).resolve().parents[2]
AALTO = ROOT / "third_party" / "aaltonomous-humanoid"
sys.path.insert(0, str(AALTO))

from aaltonomous.scene.scene import Scene                      # noqa: E402
from aaltonomous.sim.aalto_task import layout as LAY           # noqa: E402

CFG = Path(__file__).with_name("venue_measured.yaml")
ARM = [f"{s}_{j}_joint" for s in ("left", "right") for j in
       ("shoulder_pitch", "shoulder_roll", "shoulder_yaw", "elbow", "wrist_roll", "wrist_pitch", "wrist_yaw")]
HAND = ([f"left_hand_{j}_joint" for j in ("thumb_0", "thumb_1", "thumb_2", "middle_0", "middle_1", "index_0", "index_1")]
        + [f"right_hand_{j}_joint" for j in ("thumb_0", "thumb_1", "thumb_2", "index_0", "index_1", "middle_0", "middle_1")])
TORSO_IN_PELVIS = np.array([-0.0039635, 0.0, 0.044])          # waist joints at 0 (MJCF waist_roll_link pos)
ENV_CONTYPE, ENV_CONAFF = 1, 3                                  # env collides with env and robot
ROBOT_CONTYPE, ROBOT_CONAFF = 2, 1                              # robot collides with env only
HEAD_GROUP = 2                                                  # geom group the head camera does not render


def load_cfg(path=CFG):
    return yaml.safe_load(open(path))


def rgb(c, a=1.0):
    return [c[0] / 255.0, c[1] / 255.0, c[2] / 255.0, a]


# ------------------------------------------------------------------------------------------------ geometry
def scene_yaml(cfg, out=ROOT / "artifacts" / "mujoco" / "scene_measured.yaml"):
    """Aalto's scene.yaml with the measured bins and the venue layout region -> path (Aalto format, so Scene.load,
    layout.evaluate and the policy (AALTO_SCENE, when patched) read it unchanged)."""
    s = yaml.safe_load(open(AALTO / "aaltonomous" / "scene" / "scene.yaml"))
    t, b = cfg["table"], cfg["bins"]
    mo = s["counter"]["mat_origin_in_pelvis"]
    x_near = t["robot_to_table_edge"] + b["table_edge_to_bins"]          # pelvis x of the bins' near edge
    cx = x_near + b["outer_size"] / 2
    pitch = b["outer_size"] + b["gap"]
    jit = b.get("jitter") or {}                                          # dr.py: per-bin (dx, dy) in the pelvis frame
    s["bins"].update(outer_size=[b["outer_size"]] * 2, wall_height=b["wall_height"],
                     wall_thickness=b["wall_thickness"],
                     centers={n: [round(-mo[1] + y + jit.get(n, (0, 0))[1], 4),          # mat x = pelvis y + 0.45
                                  round(cx - mo[0] + jit.get(n, (0, 0))[0], 4)]
                              for n, y in (("left", pitch), ("center", 0.0), ("right", -pitch))})
    s["layout"].update(cfg["layout"])
    s["counter"]["counter_size"] = [t["size"][1], t["size"][0]]
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w") as f:
        f.write("# generated by sim/mujoco/build.py from Aalto's scene.yaml + sim/mujoco/venue_measured.yaml\n")
        yaml.safe_dump(s, f, sort_keys=False)
    return out


def head_T_pelvis_optical(cfg):
    """Calibration.yaml head pose, turned like the venue look, at the measured height -> 4x4 (OpenCV optical frame)."""
    T = np.asarray(yaml.safe_load(open(AALTO / "aaltonomous" / "interface" / "calibration.yaml"))
                   ["cameras"]["head"]["T_pelvis_optical"], float)
    c = cfg["camera"]

    def r(axis, deg):
        a = np.radians(float(deg))
        co, si = np.cos(a), np.sin(a)
        return {"x": np.array([[1, 0, 0], [0, co, -si], [0, si, co]]), "y": np.array([[co, 0, si], [0, 1, 0], [-si, 0, co]]),
                "z": np.array([[co, -si, 0], [si, co, 0], [0, 0, 1]])}[axis]
    T = T.copy()
    T[:3, :3] = T[:3, :3] @ r("x", -c["pitch_down_deg"]) @ r("z", c["roll_deg"]) @ r("y", c["yaw_deg"])
    T[1, 3] += c["shift_y"]
    table_z = cfg["table"]["height"] - cfg["robot"]["pelvis_height"]          # table top in the pelvis frame
    T[2, 3] = table_z + c["above_table"]
    return T


def triangle_vertices(size):
    """Equilateral prism, altitude = size, height = size, centroid at the origin, apex towards +y (Aalto's mesh)."""
    a, h = size, size / 2
    side = 2 * a / np.sqrt(3)
    tri = [(0.0, 2 * a / 3), (-side / 2, -a / 3), (side / 2, -a / 3)]
    return [v for z in (-h, h) for (x, y) in tri for v in (x, y, z)]


# ------------------------------------------------------------------------------------------------ model
def build_spec(cfg=None, colors="venue"):
    cfg = cfg or load_cfg()
    sc = Scene.load(str(scene_yaml(cfg)))
    spec = mujoco.MjSpec.from_file(str(ROOT / cfg["robot"]["mjcf"]))
    ph = cfg["robot"]["pelvis_height"]

    # --- robot: fixed pelvis, legs + waist locked (joints removed), position actuators on the 28 arm/hand joints
    keep = set(ARM + HAND)
    for j in list(spec.joints):
        if j.name not in keep:
            spec.delete(j)
    for a in list(spec.actuators):
        spec.delete(a)
    spec.body("pelvis").pos = [0.0, 0.0, ph]
    lean = float(cfg["robot"].get("lean_deg", 0.0))   # torso leaning towards the table (dr.py mode "lean"): the whole
    if lean:                                          # robot pitches about the pelvis, camera and arms together
        a = np.radians(lean) / 2
        spec.body("pelvis").quat = [float(np.cos(a)), 0.0, float(np.sin(a)), 0.0]
    g = cfg["robot"]["gains"]
    for name in ARM + HAND:
        j = spec.joint(name)
        grp = g["hand"] if "hand" in name else (g["wrist"] if "wrist" in name else g["arm"])
        j.armature = grp["armature"]
        a = spec.add_actuator()
        a.name, a.target, a.trntype = name, name, mujoco.mjtTrn.mjTRN_JOINT
        a.gaintype, a.biastype = mujoco.mjtGain.mjGAIN_FIXED, mujoco.mjtBias.mjBIAS_AFFINE
        a.gainprm[0] = grp["kp"]
        a.biasprm[0], a.biasprm[1], a.biasprm[2] = 0.0, -grp["kp"], -grp["kd"]
        a.ctrllimited, a.ctrlrange = 1, list(j.range)
        if j.actfrcrange[1] > 0:
            a.forcelimited, a.forcerange = 1, list(j.actfrcrange)
    for b in spec.bodies:
        if any(k in b.name for k in ("shoulder", "elbow", "wrist", "hand")):
            b.gravcomp = 1.0
    for geom in spec.geoms:
        if geom.contype or geom.conaffinity:          # collision copies: never drawn (group 3)
            geom.contype, geom.conaffinity = ROBOT_CONTYPE, ROBOT_CONAFF
            geom.condim = 4
            geom.friction = [1.0, 0.01, 0.0001]
            geom.group = 3
        elif geom.meshname in ("head_link", "logo_link"):
            geom.group = HEAD_GROUP                    # the head shell: not seen by the head camera (it looks out of it)
        elif "hand" in geom.meshname:
            geom.rgba = [0.12, 0.12, 0.13, 1.0]        # the real Dex3 hands are black

    # --- head camera on torso_link (MuJoCo camera: x right, y up, looking along -z)
    T = head_T_pelvis_optical(cfg)
    R_mj = T[:3, :3] @ np.diag([1.0, -1.0, -1.0])
    q = np.zeros(4)
    mujoco.mju_mat2Quat(q, R_mj.flatten())
    c = cfg["camera"]
    hc = spec.body("torso_link").add_camera(name="head_d435", pos=list(T[:3, 3] - TORSO_IN_PELVIS), quat=list(q),
                                            resolution=[c["width"], c["height"]])
    if "cx" in c:                                   # full pinhole intrinsics (Aalto's calibration.yaml K)
        px = 1e-5                                   # sensor pixel size (m); only the ratios matter
        hc.sensor_size = [c["width"] * px, c["height"] * px]
        hc.focal_pixel = [c["fx"], c["fy"]]
        # MuJoCo's principal offset has the opposite sign of OpenCV's (cx, cy) - centre (checked: deprojecting the
        # render with Aalto's K puts the table within 1 mm and a cube within ~1 mm; the other signs are 5-11 mm off)
        hc.principal_pixel = [-(c["cx"] - c["width"] / 2), -(c["cy"] - c["height"] / 2)]
    else:
        hc.fovy = float(np.degrees(2 * np.arctan(c["height"] / 2 / c["fy"])))

    # --- world: floor, lights, table, bins, objects, a third-person camera
    wb = spec.worldbody
    for geom in list(wb.geoms):                      # the MJCF's own checker floor and light: replaced
        if geom.name == "floor":
            spec.delete(geom)
    for light in list(wb.lights):
        spec.delete(light)
    wb.add_geom(name="floor", type=mujoco.mjtGeom.mjGEOM_PLANE, size=[3, 3, 0.1], rgba=[0.35, 0.35, 0.38, 1],
                contype=ENV_CONTYPE, conaffinity=ENV_CONAFF)
    li = cfg.get("lights") or {}                     # dr.py: key/fill scale, key direction, ambient
    ks, fs = li.get("key_scale", 1.0), li.get("fill_scale", 1.0)
    wb.add_light(name="key", pos=[1.4, -0.95, 2.8], dir=li.get("key_dir", [-0.4, 0.3, -1.0]),
                 type=mujoco.mjtLightType.mjLIGHT_DIRECTIONAL,
                 diffuse=[0.5 * ks, 0.5 * ks, 0.48 * ks], specular=[0.1, 0.1, 0.1], castshadow=1)
    wb.add_light(name="fill", pos=[0.3, 0.5, 2.5], dir=[0.0, 0.0, -1.0], type=mujoco.mjtLightType.mjLIGHT_DIRECTIONAL,
                 diffuse=[0.15 * fs] * 3, specular=[0, 0, 0], castshadow=0)
    t = cfg["table"]
    top = t["height"]
    tx = t["robot_to_table_edge"] + t["size"][0] / 2
    wb.add_geom(name="table", type=mujoco.mjtGeom.mjGEOM_BOX, pos=[tx, 0, top - t["thickness"] / 2],
                size=[t["size"][0] / 2, t["size"][1] / 2, t["thickness"] / 2], rgba=rgb(t["rgb"]),
                friction=[t["friction"], 0.005, 0.0001], contype=ENV_CONTYPE, conaffinity=ENV_CONAFF)
    for k, y in enumerate((-0.45, 0.45)):            # visual legs only
        wb.add_geom(name=f"table_leg{k}", type=mujoco.mjtGeom.mjGEOM_BOX, pos=[tx + 0.2, y, (top - t["thickness"]) / 2],
                    size=[0.02, 0.02, (top - t["thickness"]) / 2], rgba=rgb(t["rgb"]), contype=0, conaffinity=0)
    b = cfg["bins"]
    s2, w, th = b["outer_size"] / 2, b["wall_thickness"], b["wall_height"]
    for name in ("left", "center", "right"):
        p = sc.mat_to_pelvis(np.r_[sc.cfg["bins"]["centers"][name], 0.0])
        body = wb.add_body(name=f"bin_{name}", pos=[p[0], p[1], top])
        kw = dict(type=mujoco.mjtGeom.mjGEOM_BOX, contype=ENV_CONTYPE, conaffinity=ENV_CONAFF, friction=[0.8, 0.005, 0.0001])
        body.add_geom(name=f"bin_{name}_floor", pos=[0, 0, 0.0015], size=[s2, s2, 0.0015], rgba=rgb(b["liner_rgb"]), **kw)
        for side, (pos, size) in {"near": ([-s2 + w / 2, 0, th / 2], [w / 2, s2, th / 2]),
                                  "far": ([s2 - w / 2, 0, th / 2], [w / 2, s2, th / 2]),
                                  "l": ([0, s2 - w / 2, th / 2], [s2, w / 2, th / 2]),
                                  "r": ([0, -s2 + w / 2, th / 2], [s2, w / 2, th / 2])}.items():
            body.add_geom(name=f"bin_{name}_{side}", pos=pos, size=size, rgba=rgb(b["rgb"]), **kw)

    o = cfg["objects"]
    size = sc.cfg["objects"]["size"]
    spec.add_mesh(name="tri_prism", uservert=triangle_vertices(size))
    cols = colors if isinstance(colors, dict) else o["colors"][colors]     # dr.py passes RGB values
    names = LAY.object_names(sc)
    for i, n in enumerate(names):
        colr, shape, _ = LAY.parse_name(n)
        p, _ = LAY.park_pose(sc, i, len(names))
        body = wb.add_body(name=n, pos=list(p + LAY.PELVIS_W))
        body.add_freejoint(name=n)
        kw = dict(rgba=rgb(cols[colr]), mass=o["mass"], friction=[o["friction"], 0.005, 0.0001], condim=4,
                  contype=ENV_CONTYPE, conaffinity=ENV_CONAFF)
        if shape == "cube":
            body.add_geom(name=n, type=mujoco.mjtGeom.mjGEOM_BOX, size=[size / 2] * 3, **kw)
        elif shape == "cylinder":
            body.add_geom(name=n, type=mujoco.mjtGeom.mjGEOM_CYLINDER, size=[size / 2, size / 2, 0], **kw)
        else:
            body.add_geom(name=n, type=mujoco.mjtGeom.mjGEOM_MESH, meshname="tri_prism", **kw)

    wb.add_camera(name="overview", pos=[1.25, -0.75, 1.55], xyaxes=[0.5, 0.866, 0, -0.45, 0.26, 0.85], fovy=45)

    # --- options
    spec.option.timestep = cfg["physics"]["timestep"]
    spec.option.integrator = mujoco.mjtIntegrator.mjINT_IMPLICITFAST
    spec.option.cone = mujoco.mjtCone.mjCONE_ELLIPTIC
    spec.option.impratio = 10.0
    spec.visual.global_.offwidth, spec.visual.global_.offheight = 1280, 960
    spec.visual.quality.shadowsize = 4096
    spec.visual.headlight.ambient = [li.get("ambient", 0.3)] * 3
    spec.visual.headlight.diffuse = [0.15, 0.15, 0.15]
    spec.visual.headlight.specular = [0.0, 0.0, 0.0]
    return spec, sc


def build(cfg=None, colors="venue"):
    """-> (MjModel, Scene of the measured geometry)."""
    spec, sc = build_spec(cfg, colors)
    return spec.compile(), sc


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--colors", default="venue")
    ap.add_argument("--xml", default=None, help="also write the compiled scene as MJCF")
    a = ap.parse_args()
    spec, sc = build_spec(colors=a.colors)
    m = spec.compile()
    print(f"model: nq {m.nq} nu {m.nu} nbody {m.nbody} ngeom {m.ngeom}; bins {sc.cfg['bins']['centers']} "
          f"wall {sc.cfg['bins']['wall_height']}; camera {head_T_pelvis_optical(load_cfg())[:3, 3].round(4)}")
    if a.xml:
        Path(a.xml).write_text(spec.to_xml())
        print("wrote", a.xml)


if __name__ == "__main__":
    main()
